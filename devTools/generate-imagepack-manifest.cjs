/* Build the file lists for the selectable image packs (imagepacks/<id>/ overlays of img/).
 * The game loads a pack's copy of an img/ sprite only when the pack has that file, so a pack never
 * causes 404s for sprites it does not replace. Run by compile.sh; output is committed. */
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
/* id -> label. Order does not matter here; the game decides priority. */
const PACKS = {
	au: "Aoki Utage (Fem)",
	aumasc: "Aoki Utage (Masc)",
	mysterious: "Mysterious (combat sprites)",
};

function scan(dir, rel = "") {
	const out = {};
	const walk = (d, r) => {
		for (const entry of fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
			const childRel = r ? `${r}/${entry.name}` : entry.name;
			if (entry.isDirectory()) walk(path.join(d, entry.name), childRel);
			else if (/\.(png|gif|jpe?g|webp|svg)$/i.test(entry.name)) (out[r] = out[r] || []).push(entry.name);
		}
	};
	walk(dir, rel);
	return out;
}

const manifest = {};
for (const [id, label] of Object.entries(PACKS)) {
	const dir = path.join(root, "imagepacks", id);
	manifest[id] = { label, dir: `imagepacks/${id}/`, files: fs.existsSync(dir) ? scan(dir) : {} };
}
const output = `/* Generated by devTools/generate-imagepack-manifest.cjs. Files per directory, relative to img/. */\nwindow.ImagePackManifest = ${JSON.stringify(manifest)};\n`;
const destination = path.join(root, "game/03-JavaScript/imagepacks-manifest.js");
if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== output) fs.writeFileSync(destination, output);
